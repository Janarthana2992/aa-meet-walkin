-- 3. Tables
CREATE TABLE "public"."association_members" (
  "member_login_id" varchar(100) PRIMARY KEY NOT NULL,
  "full_name" varchar(255) NOT NULL,
  "email" varchar(200) UNIQUE NOT NULL,
  "mobile" varchar(20),
  "course" "public"."course_type",
  "stream" "public"."stream_type",
  "graduating_year" integer,
  "city" varchar(100),
  "state" varchar(100),
  "pincode" varchar(20),
  "membership_type" "public"."association_membership_type" NOT NULL,
  "imported_at" timestamp DEFAULT (now()),
  "created_at" timestamp NOT NULL DEFAULT (now()),
  "updated_at" timestamp NOT NULL DEFAULT (now())
);

CREATE TABLE "public"."events" (
  "event_id" INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  "event_name" varchar(255) NOT NULL,
  "event_type" "public"."event_type" NOT NULL,
  "chapter_name" varchar(150) NOT NULL,
  "venue" varchar(255),
  "event_date" date NOT NULL,
  "event_time" varchar(100),
  "description" text,
  "is_active" boolean NOT NULL DEFAULT true,
  "created_at" timestamp NOT NULL DEFAULT (now()),
  "updated_at" timestamp NOT NULL DEFAULT (now())
);

CREATE TABLE "public"."event_fee_configurations" (
  "fee_configuration_id" INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  "event_id" integer NOT NULL REFERENCES "public"."events" ("event_id") ON DELETE CASCADE DEFERRABLE INITIALLY IMMEDIATE,
  "min_graduating_year" integer NOT NULL,
  "max_graduating_year" integer NOT NULL,
  "membership_type" "public"."registration_membership_type" NOT NULL,
  "registration_fee" decimal(10,2) NOT NULL DEFAULT 0,
  "display_order" integer DEFAULT 0,
  "is_active" boolean NOT NULL DEFAULT true,
  "created_at" timestamp NOT NULL DEFAULT (now()),
  "updated_at" timestamp NOT NULL DEFAULT (now())
);

CREATE TABLE "public"."event_pre_registrations" (
  "pre_registration_id" INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  "event_id" integer NOT NULL REFERENCES "public"."events" ("event_id") ON DELETE CASCADE DEFERRABLE INITIALLY IMMEDIATE,
  "member_login_id" varchar(100),
  "full_name" varchar(255) NOT NULL,
  "course" varchar(100),
  "stream" varchar(100),
  "graduating_year" integer,
  "email" varchar(200) NOT NULL,
  "mobile" varchar(20),
  "membership_type" "public"."registration_membership_type" NOT NULL DEFAULT 'UNREGISTERED_MEMBER',
  "food_preference" varchar(100),
  "accompanying_alumni_count" integer NOT NULL DEFAULT 0,
  "accompanying_family_count" integer NOT NULL DEFAULT 0,
  "response_status" "public"."pre_registration_response_status" NOT NULL,
  "imported_at" timestamp DEFAULT (now()),
  "created_at" timestamp NOT NULL DEFAULT (now()),
  "updated_at" timestamp NOT NULL DEFAULT (now())
);

CREATE TABLE "public"."event_registrations" (
  "registration_id" INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  "event_id" integer NOT NULL REFERENCES "public"."events" ("event_id") ON DELETE CASCADE DEFERRABLE INITIALLY IMMEDIATE,
  "member_login_id" varchar(100),
  "full_name" varchar(255) NOT NULL,
  "email" varchar(200) NOT NULL,
  "mobile" varchar(20),
  "course" varchar(100),
  "stream" varchar(100),
  "graduating_year" integer,
  "membership_type_used" "public"."registration_membership_type" NOT NULL,
  "registration_source" "public"."registration_source" NOT NULL,
  "recognized_member" boolean NOT NULL DEFAULT false,
  "food_preference" varchar(100),
  "accompanying_alumni_count" integer NOT NULL DEFAULT 0,
  "accompanying_family_count" integer NOT NULL DEFAULT 0,
  "registration_fee" decimal(10,2) NOT NULL DEFAULT 0,
  "voluntary_contribution" decimal(10,2) NOT NULL DEFAULT 0,
  "total_amount" decimal(10,2) NOT NULL DEFAULT 0,
  "payment_required" boolean NOT NULL DEFAULT true,
  "payment_mode" "public"."payment_mode",
  "payment_confirmed" boolean NOT NULL DEFAULT false,
  "utr_last4" varchar(4),
  "paid_at" timestamp,
  "checked_in_at" timestamp NOT NULL DEFAULT (now()),
  "created_at" timestamp NOT NULL DEFAULT (now()),
  "updated_at" timestamp NOT NULL DEFAULT (now())
);

