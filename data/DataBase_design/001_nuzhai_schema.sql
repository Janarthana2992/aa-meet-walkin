-- 6. Automatic updated_at Triggers
CREATE OR REPLACE FUNCTION "public"."set_updated_at"()
RETURNS TRIGGER
LANGUAGE plpgsql
SET search_path = public
AS $$
BEGIN
  NEW.updated_at = now();
  RETURN NEW;
END;
$$;

CREATE TRIGGER "trg_association_members_updated_at"
  BEFORE UPDATE ON "public"."association_members"
  FOR EACH ROW EXECUTE FUNCTION "public"."set_updated_at"();

CREATE TRIGGER "trg_events_updated_at"
  BEFORE UPDATE ON "public"."events"
  FOR EACH ROW EXECUTE FUNCTION "public"."set_updated_at"();

CREATE TRIGGER "trg_event_fee_configurations_updated_at"
  BEFORE UPDATE ON "public"."event_fee_configurations"
  FOR EACH ROW EXECUTE FUNCTION "public"."set_updated_at"();

CREATE TRIGGER "trg_event_pre_registrations_updated_at"
  BEFORE UPDATE ON "public"."event_pre_registrations"
  FOR EACH ROW EXECUTE FUNCTION "public"."set_updated_at"();

CREATE TRIGGER "trg_event_registrations_updated_at"
  BEFORE UPDATE ON "public"."event_registrations"
  FOR EACH ROW EXECUTE FUNCTION "public"."set_updated_at"();

